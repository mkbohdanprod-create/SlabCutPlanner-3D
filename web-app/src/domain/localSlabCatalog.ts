import type { MaterialType } from './types';
import type { SlabDecor } from './slabCatalog';

/**
 * ВЛАСНІ КАРТКИ КАТАЛОГУ СЛЯБІВ (№158, власник 08.09: «добав сюди 1 матеріал
 * зразу з фотками»).
 *
 * Навіщо. Каталог тягнеться з довідника номенклатур; коли сервіс недоступний
 * (а в розробці він недоступний завжди), у вікні «Матеріал» лишається сама
 * лише картка «Матеріал замовника» — показати чи спробувати нема на чому.
 * Ці картки живуть у застосунку і НЕ залежать від довідника.
 *
 * Чим вони НЕ є. Це не номенклатура: артикула немає, ціни немає, у прорахунок
 * такий сляб іде як натуральний камінь із ручним габаритом — рівно так само,
 * як лист, знятий менеджером на складі. Тому й позначені окремо (`local`), і
 * стоять після реальних записів довідника.
 *
 * Фото. Два кадри ОДНОГО листа: без підсвітки і з підсвіткою (просвітний
 * камінь). Кадр другого ідентичний першому — інакше при перемиканні малюнок
 * стрибне, бо UV-матриця в розкрої не змінюється. Файли лежать у
 * `public/slabs/…` і потрапляють у збірку як є.
 */
export interface LocalSlabCard extends SlabDecor {
  /** Фото того самого листа з підсвіткою */
  photoBacklit?: string;
  /** Ознака «наша власна картка, не з довідника» — для підпису в UI */
  local: true;
}

