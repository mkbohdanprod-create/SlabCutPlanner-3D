/** Ділянка для рядка заявки: null — не послуга (матеріал, МЕС-4). */
export function areaOfCode(code: string, name = ''): string | null {
  const e = CODE_AREA[code];
  if (!e) return null;
  // ГІПОТЕЗА: гідроабразив — окрема ділянка; у CSV-2026 вода сидить у «Пильний центр»
  if (e[0] === 'Пильний центр' && /водою/i.test(name || e[2])) return 'Порізка водою';
  return e[0];
}
